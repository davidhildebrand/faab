"""Edit the LMCs tab of a synced workbook in place of a rebuild (David 2026-11-07; proofreaders work in the tab, so it is
edited, not regenerated by lmc_tab.py):
  --drop-prs           remove rows whose cell is a photoreceptor of the PRs tab (class R1-R6, R1-R6?, R7, R8 or R7/R8,
                       by root_id_curr or root_id_orig): the 2026-11-01 LMC search let R7s through (they get R8 / R1-R6
                       synapses and have lamina input and medulla output); they are tracked in the PRs tab
  --move ROOT:TYPE     move a row to the 'putative TYPE' block (putative_type TYPE; annotation = the SeaTable column's
                       label when it ends in TYPE; the note pair 'SeaTable says Lx' / 'the automatic typing says Ly ...'
                       dropped once SeaTable and the call agree), placed among the annotated rows by status
  --drop ROOT[:why]    remove a cell that is not an LMC after all (by root_id_curr or root_id_orig; repeatable)
Then every block line is recounted and, with --links, the links of the changed blocks are rebuilt (cells colored by
confidence, as lmc_tab.py does; CAVE state uploads only, >= 2 s apart). Rows keep their styles, links and heights.
Writes figures/sheets/<stamp>_FAABopticlobetargets-LMCs.xlsx (the LMCs tab alone, to import).
Usage: lmcs_tab_edit.py BOOK.xlsx [--drop-prs] [--move ROOT:TYPE ...] [--links]"""
import argparse
import datetime
import os
import re
import sys
import time

import openpyxl

from faab.config import fig
from faab.partners.sheet import cell_text as s, utc_stamp
from faab.pr.prs_tab import restore, snapshot

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lmc_tab import COLOR, CONF_RANK, STATUS_RANK, TYPES  # noqa: E402

PR_CLASSES = ("R1-R6", "R1-R6?", "R7", "R8", "R7/R8")
NAMES = {f"putative {t}": t for t in TYPES} | {"LMC, type unclear": "unclear"}


def table_rows(ws):
    """(row, {column: value}) of every data row of a tab (header = the last row above holding 'root_id_orig')"""
    hdr = None
    for r in range(1, ws.max_row + 1):
        vals = [s(ws.cell(r, c).value) for c in range(1, ws.max_column + 1)]
        if "root_id_orig" in vals:
            hdr = {v: i for i, v in enumerate(vals) if v}
            continue
        i0 = hdr.get("root_id_orig") if hdr else None
        if i0 is not None and i0 < len(vals) and vals[i0].isdigit():
            yield r, {k: vals[i] for k, i in hdr.items() if i < len(vals)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("book")
    ap.add_argument("--drop-prs", action="store_true")
    ap.add_argument("--move", nargs="+", action="extend", default=[])  # repeatable: --move A:L2 --move B:L2
    ap.add_argument("--drop", nargs="+", action="extend", default=[])  # ROOT[:reason], repeatable
    ap.add_argument("--links", action="store_true")
    a = ap.parse_args()
    wb = openpyxl.load_workbook(a.book)
    ws = wb["LMCs"]
    width = ws.max_column

    # layout: a list of items in order - ('row', r) for title / header / blank / note rows, ('block', name) per block
    hdr, items, blocks, cur = None, [], {}, None
    for r in range(1, ws.max_row + 1):
        first = s(ws.cell(r, 1).value)
        vals = [s(ws.cell(r, c).value) for c in range(1, width + 1)]
        name = first.split(":")[0]
        if name in NAMES:
            cur = NAMES[name]
            blocks[cur] = dict(title=r, header=None, rows=[])
            items.append(("title", cur))
        elif "root_id_orig" in vals:
            hdr = {v: i + 1 for i, v in enumerate(vals) if v}
            blocks[cur]["header"] = r
            items.append(("header", cur))
        elif cur and first.isdigit():
            if not blocks[cur]["rows"]:
                items.append(("data", cur))
            blocks[cur]["rows"].append(r)
        else:
            items.append(("row", r))
            cur = None if first.startswith("note:") else cur
    col = lambda name: hdr[name]
    val = lambda r, name: s(ws.cell(r, col(name)).value)
    snap = {r: snapshot(ws, r) for r in range(1, ws.max_row + 1)}
    data = {b: [r for r in v["rows"]] for b, v in blocks.items()}
    changed, log = set(), []

    if a.drop_prs:
        prs = {}
        for r, x in table_rows(wb["PRs"]):
            if x.get("class", "") in PR_CLASSES:
                for k in ("root_id_curr", "root_id_orig"):
                    if x.get(k, "").isdigit():
                        prs.setdefault(x[k], f"PRs r{r} {x['class']}")
        for b, rows in data.items():
            keep = []
            for r in rows:
                hit = prs.get(val(r, "root_id_curr")) or prs.get(val(r, "root_id_orig"))
                if hit:
                    log.append(f"removed r{r} {val(r, 'root_id_curr')} (block {b}, {val(r, 'confidence')}): {hit}")
                    changed.add(b)
                else:
                    keep.append(r)
            data[b] = keep

    for spec in a.drop:  # ROOT[:reason] - a cell that is not an LMC after all
        root, _, reason = spec.partition(":")
        hit = [(b, r) for b, rows in data.items() for r in rows if root in (val(r, "root_id_curr"), val(r, "root_id_orig"))]
        if not hit:
            sys.exit(f"--drop: {root} not found in the LMCs tab")
        for b, r in hit:
            data[b].remove(r)
            changed.add(b)
            log.append(f"removed r{r} {val(r, 'root_id_curr')} (block {b}, {val(r, 'confidence')}): {reason or 'not an LMC'}")

    edits = {}  # row -> {column: new value}
    for m in a.move:
        root, t = m.split(":")
        src = next((b for b, rows in data.items() for r in rows if root in (val(r, "root_id_curr"), val(r, "root_id_orig"))), None)
        if src is None:
            sys.exit(f"--move: {root} not found in the LMCs tab")
        r = next(r for r in data[src] if root in (val(r, "root_id_curr"), val(r, "root_id_orig")))
        data[src].remove(r)
        e = {"putative_type": t}
        label = val(r, "SeaTable").split(":", 1)[-1].strip()
        if re.search(rf"\b{t}$", label):
            e["annotation"] = label
        notes = [p.strip() for p in val(r, "notes").split(";") if p.strip()]
        agree = re.search(rf"\b{t}$", label) is not None
        e["notes"] = "; ".join(p for p in notes if not (agree and re.match(r"^(SeaTable says L[1-5]|the automatic typing says)", p)))
        edits[r] = e
        rank = lambda q: (CONF_RANK.get(val(q, "confidence"), 9), STATUS_RANK.get(val(q, "status").lower(), 8)
                          if val(q, "confidence") == "annotated" else 0)
        me = (CONF_RANK["annotated"], STATUS_RANK.get(val(r, "status").lower(), 8))
        dst = data[t]
        pos = next((i for i, q in enumerate(dst) if rank(q) > me), len(dst))
        dst.insert(pos, r)
        changed |= {src, t}
        log.append(f"moved r{r} {val(r, 'root_id_curr')} from {src} to {t} (position {pos + 1} of {len(dst)}): {e}")

    # counts per block, from the rows' confidence
    title_text = {}
    for b, rows in data.items():
        conf = [val(r, "confidence") for r in rows]
        name = next(k for k, v in NAMES.items() if v == b)
        title_text[b] = f"{name}: {len(rows)} cells (" + ", ".join(f"{k} {conf.count(k)}" for k in CONF_RANK) + ")"

    links = {}
    if a.links and changed:
        from faab import nglink
        from faab.clients.cave import client as cave_client, throttle
        client, t = cave_client(), 0.0
        for b in sorted(changed):
            rows = data[b]
            neurons = [{"name": f"{'putative ' + b if b in TYPES else 'type unclear'}: {k} "
                                f"({sum(val(r, 'confidence') == k for r in rows)})", "color": COLOR[k],
                        "ids": [val(r, "root_id_curr") for r in rows if val(r, "confidence") == k]}
                       for k in CONF_RANK if any(val(r, "confidence") == k for r in rows)]
            spec = {"meshes": [{"kind": "OL", "segments": ["11", "14", "21", "24"], "alpha": 0.12}], "neurons": neurons,
                    "layout": "3d", "select": neurons[0]["name"]}
            t = throttle(t)
            links[b] = client.state.build_neuroglancer_url(
                client.state.upload_state_json(nglink.clean_state(nglink.build(spec))),
                ngl_url="https://spelunker.cave-explorer.org")
            t = time.time()
            log.append(f"link {b}: {links[b]}")

    # write the new tab: same items in order, blocks with their new rows
    out = wb.create_sheet("LMCs_new")
    for k, d in ws.column_dimensions.items():
        out.column_dimensions[k].width = d.width
    out.sheet_view.showGridLines = ws.sheet_view.showGridLines
    out.freeze_panes = ws.freeze_panes
    now = datetime.datetime.now(datetime.timezone.utc)
    r_out = 0
    for kind, ref in items:
        rows = [ref] if kind == "row" else [blocks[ref]["title"]] if kind == "title" else \
            [blocks[ref]["header"]] if kind == "header" else data[ref]
        for r in rows:
            r_out += 1
            restore(out, r_out, snap[r])
            if kind == "title":
                out.cell(r_out, 1).value = title_text[ref]
                if ref in links:
                    c = out.cell(r_out, col("link"))
                    c.hyperlink = links[ref]
                    c.value = links[ref]
            elif kind == "data" and r in edits:
                for name, v in edits[r].items():
                    out.cell(r_out, col(name)).value = v or None
            elif kind == "row" and r == 1:
                out.cell(1, 1).value = re.sub(r"\(updated [^)]*\)", f"(updated {now:%Y-%m-%d %H:%M} UTC)", s(snap[r][0][0][0]))
            elif kind == "row" and s(snap[r][0][0][0]).startswith("note: to confirm") and a.drop_prs:
                c = out.cell(r_out, 1)
                if "Photoreceptor axons" not in s(c.value):
                    c.value = s(c.value) + " Photoreceptor axons (tracked in the PRs tab) were removed (2026-11-07)."
    for w in list(wb.worksheets):
        if w is not out:
            wb.remove(w)
    out.title = "LMCs"
    path = fig(f"sheets/{utc_stamp()}_FAABopticlobetargets-LMCs.xlsx")
    wb.save(path)
    print("\n".join(log))
    print({b: title_text[b] for b in data})
    print(f"wrote {path}: {r_out} rows (was {ws.max_row})")


if __name__ == "__main__":
    main()
